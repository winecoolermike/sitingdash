#!/usr/bin/env bash
# Maintenance helper (not a build step): copy SitingIntel's export into data/ and refresh the
# file:// inline copies (feed + SitingDash overrides). Rebuild overrides first with tools/build-overrides.py. Usage: tools/sync-data.sh [/path/to/ohio-pilot.json]
set -euo pipefail
cd "$(dirname "$0")/.."
SRC="${1:-/workspace/sitingintel-export/ohio-pilot.json}"
python3 -c "import json,sys; json.load(open(sys.argv[1]))" "$SRC"
cp "$SRC" data/ohio-pilot.json
{
  printf '/* Generated by tools/sync-data.sh — byte-for-byte copy of data/ohio-pilot.json for file:// opens. Do not edit. */\n'
  printf 'window.SITINGDASH_INLINE = '
  cat data/ohio-pilot.json
  printf ';\n'
} > data/ohio-pilot.inline.js
{
  printf '/* Generated by tools/sync-data.sh — copy of data/sitingdash-overrides.json for file:// opens. Do not edit. */\n'
  printf 'window.SITINGDASH_OVERRIDES_INLINE = '
  cat data/sitingdash-overrides.json
  printf ';\n'
} > data/sitingdash-overrides.inline.js
echo "synced $(wc -c < data/ohio-pilot.json) bytes from $SRC"
